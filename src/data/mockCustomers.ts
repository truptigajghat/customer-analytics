/**
 * Generates deterministic, clearly-labeled DEMO placeholder metadata for the Churn Prediction UI.
 * NOTE: This is NOT a real ML inference model. It provides static illustrative placeholder data
 * until the FastAPI ML backend endpoint is connected.
 */
export function buildDemoPredictionMeta(customer: Customer): CustomerDemoPredictionMeta {
  // Deterministic illustrative placeholder lookup based on customer attributes
  let baseProb = 0.24;
  if (customer.Churn === 'Yes') baseProb = 0.84;
  else if (customer.riskTier === 'High') baseProb = 0.76;
  else if (customer.riskTier === 'Medium') baseProb = 0.46;
  else baseProb = 0.14;

  // Small deterministic variation per customer ID so different rows show distinct UI states
  const idSeed = customer.customerID
    .split('')
    .reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const offset = ((idSeed % 11) - 5) * 0.015;
  const probability = Math.min(0.96, Math.max(0.05, Number((baseProb + offset).toFixed(3))));

  const riskCategory: RiskTier =
    probability >= 0.65 ? 'High' : probability >= 0.35 ? 'Medium' : 'Low';

  const factors: ContributingFactor[] = [];

  if (customer.Contract === 'Month-to-month') {
    factors.push({
      factor: 'Month-to-Month Contract',
      detail: 'No annual commitment increases short-term cancellation flexibility.',
      impact: 'increases_risk',
      weight: 86,
    });
  } else {
    factors.push({
      factor: `${customer.Contract} Agreement`,
      detail: 'Multi-period contract structure strongly stabilizes retention.',
      impact: 'reduces_risk',
      weight: 78,
    });
  }

  if (customer.tenure < 12) {
    factors.push({
      factor: `Early Tenure (${customer.tenure} months)`,
      detail: 'Accounts under 12 months exhibit heightened sensitivity during onboarding.',
      impact: 'increases_risk',
      weight: 74,
    });
  } else {
    factors.push({
      factor: `Established Tenure (${customer.tenure} months)`,
      detail: 'Long-standing account history lowers voluntary churn propensity.',
      impact: 'reduces_risk',
      weight: 72,
    });
  }

  if (customer.PaymentMethod === 'Electronic check') {
    factors.push({
      factor: 'Electronic Check Payment',
      detail: 'Manual check settlement correlates with higher involuntary & voluntary churn.',
      impact: 'increases_risk',
      weight: 64,
    });
  } else if (customer.PaymentMethod.includes('automatic')) {
    factors.push({
      factor: 'Automated Billing Enrolled',
      detail: 'Autopay reduces billing friction and payment lapse events.',
      impact: 'reduces_risk',
      weight: 56,
    });
  }

  if (customer.InternetService === 'Fiber optic' && customer.TechSupport === 'No') {
    factors.push({
      factor: 'Fiber Tier Without Tech Support',
      detail: 'High monthly spend without proactive technical coverage elevates dissatisfaction risk.',
      impact: 'increases_risk',
      weight: 69,
    });
  }

  if (customer.OnlineSecurity === 'Yes') {
    factors.push({
      factor: 'Security Add-On Active',
      detail: 'Bundled security services increase account stickiness.',
      impact: 'reduces_risk',
      weight: 48,
    });
  }

  const actions: RetentionAction[] =
    riskCategory === 'High'
      ? [
          {
            id: 'act-1',
            title: 'Offer 1-Year Contract Migration Credit',
            description:
              'Provide a 15% loyalty discount for 6 months upon switching from month-to-month to an annual agreement.',
            priority: 'Immediate',
            estimatedImpact: 'High retention lift',
          },
          {
            id: 'act-2',
            title: 'Assign Proactive Technical Support Outreach',
            description: `Schedule a concierge service check-in following ${customer.supportTickets90d} recent support interactions.`,
            priority: 'Immediate',
            estimatedImpact: 'Reduces service friction',
          },
          {
            id: 'act-3',
            title: 'Autopay Enrollment Incentive',
            description:
              'Offer a one-time $15 bill credit for switching to automated card or bank transfer billing.',
            priority: 'Recommended',
            estimatedImpact: 'Lowers payment churn',
          },
        ]
      : riskCategory === 'Medium'
        ? [
            {
              id: 'act-4',
              title: 'Bundle Value-Added Security Protection',
              description:
                'Include complimentary 90-day Online Security trial to strengthen product adoption.',
              priority: 'Recommended',
              estimatedImpact: 'Increases stickiness',
            },
            {
              id: 'act-5',
              title: 'Quarterly Plan Optimization Review',
              description:
                'Send personalized usage summary confirming current tier alignment with actual consumption.',
              priority: 'Optional',
              estimatedImpact: 'Improves perceived value',
            },
          ]
        : [
            {
              id: 'act-6',
              title: 'Enroll in Referral & Loyalty Advocacy',
              description:
                'Account exhibits healthy stability; invite to customer referral reward program.',
              priority: 'Optional',
              estimatedImpact: 'Expansion opportunity',
            },
          ];

  return {
    probability,
    riskCategory,
    factors,
    actions,
  };
}

