"""
Data Schemas for ChurnIQ Backend
Using Python standard library dataclasses for 100% native compatibility
with Windows Smart App Control and zero external C-extension dependencies.
Matches frontend TypeScript types in src/types/
"""

from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Literal, Optional


GenderType = Literal["Female", "Male"]
ContractType = Literal["Month-to-month", "One year", "Two year"]
InternetServiceType = Literal["Fiber optic", "DSL", "No"]
PaymentMethodType = Literal[
    "Electronic check",
    "Mailed check",
    "Bank transfer (automatic)",
    "Credit card (automatic)",
]
ChurnStatusType = Literal["Yes", "No"]
RiskTierType = Literal["Low", "Medium", "High"]
CustomerSegmentType = Literal[
    "High-Value",
    "Loyal",
    "New",
    "Price-Sensitive",
    "At-Risk",
    "Lost",
]


@dataclass
class CustomerSchema:
    customerID: str
    name: str
    email: str
    gender: GenderType
    SeniorCitizen: int
    ageGroup: str
    Partner: str
    Dependents: str
    tenure: int
    PhoneService: str
    MultipleLines: str
    InternetService: str
    OnlineSecurity: str
    TechSupport: str
    StreamingTV: str
    Contract: str
    PaperlessBilling: str
    PaymentMethod: str
    MonthlyCharges: float
    TotalCharges: float
    Churn: str
    segment: str
    riskTier: str
    lastActive: str
    supportTickets90d: int

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ContributingFactor:
    factor: str
    detail: str
    impact: Literal["increases_risk", "reduces_risk"]
    weight: int

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class RetentionAction:
    id: str
    title: str
    description: str
    priority: Literal["Immediate", "Recommended", "Optional"]
    estimatedImpact: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ChurnPredictionResult:
    customerID: str
    customer: Dict[str, Any]
    churnProbability: float
    riskCategory: str
    modelReference: str
    generatedAt: str
    contributingFactors: List[Dict[str, Any]]
    suggestedActions: List[Dict[str, Any]]
    isDemoData: bool = False
    disclaimer: str = "Live Model Prediction generated by ChurnIQ Engine."

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
